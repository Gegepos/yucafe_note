  static Color get(String flavor) {
    final trimmed = flavor.trim();
    return _map[trimmed] ?? _hashColor(trimmed);
  }

  static Color _hashColor(String text) {
    int hash = 0;
    for (var i = 0; i < text.length; i++) {
      hash = text.codeUnitAt(i) + ((hash << 5) - hash);
    }
    return Color((hash & 0x00FFFFFF) | 0xFF000000);
  }
